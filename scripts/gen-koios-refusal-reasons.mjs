// gen-koios-refusal-reasons.mjs: mirrors the BE's exported Koios tool refusal-reason enum
// (koiosmatch-api docs/reference/koios-tool-refusal-reasons.json, written by `openapi:export`
// step 6 and guarded there by ToolRefusalReasonMirrorTest) into a generated TS module, so the
// FE translation guard reads the BE's list instead of a hand-copied one (KOIOS-TOOL-RESULT-KEYS-3,
// BE MINI-BUNDLE-12). Run: `npm run gen:refusal-reasons`; override the source with
// KOIOS_REFUSAL_REASONS_JSON for a worktree of the BE.
import { readFileSync, writeFileSync } from 'node:fs'

const SRC = process.env.KOIOS_REFUSAL_REASONS_JSON ?? '../koiosmatch-api/docs/reference/koios-tool-refusal-reasons.json'
const OUT = 'src/components/layout/koios/toolRefusalReasons.generated.ts'
const SLUG = /^[a-z][a-z0-9_]*$/

// Reads the flat JSON array and refuses anything that is not a list of snake_case slugs.
let raw
try {
  raw = JSON.parse(readFileSync(SRC, 'utf8'))
} catch (err) {
  console.error(`gen-koios-refusal-reasons: cannot read ${SRC}: ${err instanceof Error ? err.message : String(err)}`)
  process.exit(1)
}
if (!Array.isArray(raw) || raw.length === 0 || raw.some(s => typeof s !== 'string' || !SLUG.test(s))) {
  console.error(`gen-koios-refusal-reasons: ${SRC} is not a non-empty array of snake_case slugs`)
  process.exit(1)
}

// Sorted and unique, so the generated module is stable across runs.
const slugs = [...new Set(raw)].sort()
const body = [
  '// GENERATED by scripts/gen-koios-refusal-reasons.mjs from koiosmatch-api/docs/reference/koios-tool-refusal-reasons.json',
  '// (the BE ToolRefusalReason enum, exported by openapi:export). Do not edit by hand: run `npm run gen:refusal-reasons`.',
  'export const BE_TOOL_REFUSAL_REASON_SLUGS: readonly string[] = [',
  ...slugs.map(s => `  '${s}',`),
  ']',
  '',
].join('\n')
writeFileSync(OUT, body)
console.log(`gen-koios-refusal-reasons: ${slugs.length} slugs written to ${OUT}`)
