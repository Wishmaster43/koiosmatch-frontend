// gen-workflow-template-names.mjs: mirrors the BE's exported seeded workflow template names per language
// (koiosmatch-api docs/reference/workflow-template-names.json, written by `openapi:export` and guarded there by
// WorkflowTemplateNamesMirrorTest) into a generated TS module, so the FE resolves a workflow's seeded name through its
// template_key instead of the Dutch label alone (WORKFLOW-SEED-NAMES-TEMPLATE-KEY-FE-1, BE TEMPLATE-NAMES-ENTITY-ENGLISH-1:
// a non-nl bureau stores the English name). Run: `npm run gen:workflow-template-names`; override the source with
// WORKFLOW_TEMPLATE_NAMES_JSON for a worktree of the BE.
import { readFileSync, writeFileSync } from 'node:fs'

const SRC = process.env.WORKFLOW_TEMPLATE_NAMES_JSON ?? '../koiosmatch-api/docs/reference/workflow-template-names.json'
const OUT = 'src/lib/workflowTemplateNames.generated.ts'
const SLUG = /^[a-z][a-z0-9_]*$/
const LANGS = ['nl', 'en', 'it', 'pt']
// A name is one printable line: control characters and the Unicode line separators would break the emitted literal.
const UNPRINTABLE = /[\u0000-\u001f\u007f\u2028\u2029]/

// Reads the JSON object and refuses anything that is not {snake_case key: {nl, en, it, pt: non-empty string}}.
let raw
try {
  raw = JSON.parse(readFileSync(SRC, 'utf8'))
} catch (err) {
  console.error(`gen-workflow-template-names: cannot read ${SRC}: ${err instanceof Error ? err.message : String(err)}`)
  process.exit(1)
}
const entries = raw && typeof raw === 'object' && !Array.isArray(raw) ? Object.entries(raw) : []
const wellFormed = entries.length > 0 && entries.every(([key, names]) =>
  SLUG.test(key) && names && typeof names === 'object' && LANGS.every(l => typeof names[l] === 'string' && names[l].trim() !== '' && !UNPRINTABLE.test(names[l])))
if (!wellFormed) {
  console.error(`gen-workflow-template-names: ${SRC} is not a non-empty object of snake_case keys with printable one-line nl/en/it/pt names`)
  process.exit(1)
}

// Single-quoted TS string literal.
const lit = s => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
// Sorted by key, so the generated module is stable across runs.
const sorted = entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
const body = [
  '// GENERATED by scripts/gen-workflow-template-names.mjs from koiosmatch-api/docs/reference/workflow-template-names.json',
  '// (the seeded workflow template names per language, exported by openapi:export). Do not edit by hand:',
  '// run `npm run gen:workflow-template-names`.',
  'export type TemplateSeedName = Readonly<{ nl: string; en: string; it: string; pt: string }>',
  'export const TEMPLATE_SEED_NAMES: Readonly<Record<string, TemplateSeedName>> = {',
  ...sorted.map(([key, n]) => `  ${key}: { nl: ${lit(n.nl)}, en: ${lit(n.en)}, it: ${lit(n.it)}, pt: ${lit(n.pt)} },`),
  '}',
  '',
].join('\n')
writeFileSync(OUT, body)
console.log(`gen-workflow-template-names: ${sorted.length} templates written to ${OUT}`)
